/**
 * Обновления школы для главной страницы.
 *
 * Лента заполняется по одному материалу: школа передаёт заголовок,
 * снимки и, если есть, текст. Выводятся все присланные снимки —
 * первый крупно, остальные переключаются под кадром. Формулировки
 * не переписываются (ТЗ §15), снимки не заменяются стоковыми (§23).
 */
export type NewsImage = { src: string; width: number; height: number; alt: string };

export type NewsItem = {
  title: string;
  /** Описание материала, если его передали. */
  text?: string;
  /** Телефон из текста новости, если он там есть. */
  phone?: { display: string; tel: string };
  /** Все снимки материала. Первый показывается сразу. */
  images?: readonly NewsImage[];
};

