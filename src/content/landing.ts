export type LandingItem = {
  label: string;
  /** Якорь блока главной страницы. */
  anchor?: string;
  /** Окно с краткой справкой вместо перехода на страницу. */
  info?: LandingInfo;
  /** Раскрывающийся список ступеней обучения. */
  stages?: readonly Stage[];
  /** Выделенный пункт: обводка в фирменном бордовом. */
  accent?: boolean;
};

